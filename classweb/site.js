  function getLifeWorksMonth() {
    var params = new URLSearchParams(window.location.search);
    var month = params.get("month") || "12";
    var allowedMonths = ["08", "09", "10", "11", "12"];
    var found = false;

    for (var i = 0; i < allowedMonths.length; i += 1) {
      if (allowedMonths[i] === month) {
        found = true;
        break;
      }
    }

    return found ? month : "12";
  }

